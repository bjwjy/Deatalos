import { diagnosticCardPresentation, diagnosticReference, type DisplayDiagnostic } from '@hyd/domain';

/** Shared registered codes match the workbench category and recovery guidance. */
export function networkDiagnosticGuide(): string {
  const table = diagnosticReference()
    .map(({ code, type, remedy }) => `| \`${code}\` | ${type} | ${remedy} |`)
    .join('\n');
  const samples: readonly { object?: string; diagnostic: DisplayDiagnostic }[] = [
    {
      object: '换向阀 1 的 A 口',
      diagnostic: {
        code: 'GRAPH_INCOMPLETE',
        field: '/design/components/valve/A',
        message: '油口尚未连接；草稿保留但不启动计算。',
      },
    },
    {
      diagnostic: {
        code: 'GRAPH_INCOMPLETE',
        field: '/design/components',
        message: '空白工程没有可运行的物理图。',
      },
    },
    {
      diagnostic: {
        code: 'FILE_CONFLICT',
        field: '/files',
        message: '写入期间目标发生外部修改，原文件保留。',
      },
    },
  ];
  const examples = samples
    .map(({ diagnostic, object }) => {
      const { headline, fact, next } = diagnosticCardPresentation(diagnostic, object);
      return `### ${headline}\n\n${fact}\n\n下一步：${next}\n\n技术详情中的错误码为 \`${diagnostic.code}\`。`;
    })
    .join('\n\n');
  return `# 诊断与 AI 说明

## 从报错卡开始

卡片第一行给出具体对象和问题。点「查看详情」看事实、下一步和可用操作。能确认对象时可以点「定位油口」或「定位对象」。连线问题可打开「查看接线方法」。展开「技术详情」可核对错误码、字段和原始诊断。诊断历史按操作或运行报错批次排列。

## 把本次报错交给 AI

点「复制给 AI」或「复制整批报错」，在工作区粘贴，并说明希望完成的操作。复制内容带有当前或历史标记、操作、批次、物理修订、对象、字段和原始诊断。运行报错有运行编号和步号时一并核对。复制时会隐藏识别到的本机路径和凭证，分享前请核对工程名和对象标签。

回答先说哪个对象出了什么问题、对这次操作有何影响、现在可以做什么。证据不足时指出需要补的那一项。问操作路径请查[软件操作手册](软件操作手册.md)。用户已经粘贴了报错时，按该次来源分析。

## 读取工作台中的批次

需要核对实时现场且工作台已开启「允许 AI 操作」时，用本版本客户端执行一次 \`HydraulicTool.exe --project "<工程绝对目录>" --context --summary\`。从摘要的 \`capture.diagnosticStatus\` 核对状态和当前批次号，再用内置文件工具在 \`recordDirectory\` 下打开 \`diagnosticGuideFile\`。文件按批次列出对象、问题、影响、下一步、字段和原始证据。每批最多列出 12 条，超出部分可在报错卡查看。

按「当前诊断」或用户指定的批次回答。「仅有历史」时注明批次和物理修订。「尚未检查」时说明缺少本次运行证据。没有实时连接或旧版本摘要缺少诊断字段时，可以请用户复制报错；只读取工程文件时标明已保存批次。

## 实际文案示例

${examples}

同一个错误码可对应不同现场。比如 \`GRAPH_INCOMPLETE\` 既可用于油口未连，也可用于空白工程。分析时同时看字段和原始诊断。输入框的校验要按具体参数处理，例如必须大于零的目标速度和允许为零的负载。

## 已登记的错误码和提示

| 错误码 | 界面问题类型 | 处理方向 |
| --- | --- | --- |
${table}

## 如何提出处理方案

先区分连接、输入、运行服务和文件操作，再依据原始诊断核对对象、字段与模型条件。处理方向用于定位，具体原因以该批证据为准。未知错误请列明还需哪些证据。参数修改应说明单位、允许范围、锁定条件和相关影响。建议先生成可预览候选，由用户明确确认后应用。
`;
}

/** Operation paths shipped alongside the corresponding workbench version. */
export function networkOperationGuide(): string {
  return `# 软件操作手册

这份手册供用户和打开工程文件夹的 AI 查操作。先确定工程保存批次对应的资料版本。回答先给菜单路径，再给步骤和完成时能看到的结果。实时工程问题按[诊断与 AI 说明](诊断与AI说明.md)核对当前证据。

## 工程与工作区

- **新建或打开工程**（建工程、导入旧文件）。用「文件 → 新建文件夹工程」或「文件 → 打开工程」。已有文件夹选择其中的工程.hydproj。旧 .hydx 可打开，另存时选择新工程位置。标题切换后检查打开的工程。
- **保存或另存**（存一份副本、换目录）。用「文件 → 保存」更新工程，或「文件 → 另存为」选择新位置。以实际保存提示及「已保存」状态为准。移动工程时一起移动整个目录。
- **恢复副本**（找回未保存编辑）。用「文件 → 恢复副本」，选中所需记录并打开，再另存。自动恢复频率在「工具 → 设置 → 工程恢复」。副本保存设计和布局。

## 画布与连线

- **放置和编辑元件**（找泵、把阀转向）。从元件库选元件放到画布。选中后用「编辑 → 旋转90°」或空格旋转，可用「编辑 → 撤销」恢复。
- **连线和接分支**（怎么接 A 口、为什么交叉没接上）。用「编辑 → 连接」，依次选两个油口或显式节点。需要分支时可用「编辑 → 添加分支节点」。确认画布出现实际连接，交叉处以显式接线为准。取消当前连线可按 Esc。
- **标签和吸附**（隐藏名称、调节点范围）。打开「工具 → 设置 → 画布与连线」。分别设置元件名称、油口标签、分支显示和连线吸附半径。右侧试连区可核对吸附效果。

## 参数与仿真

- **改参数或初态**（改泵排量、改油缸初始位置）。选中元件后用「视图 → 元件属性与设计初态」。按对应单位填写，应用后核对数值。物理修改后重新运行。
- **运行、暂停和复位**（开始算、看下一步、回到初始位置）。从「仿真」菜单选「运行」「暂停」「单步」或「复位」。观察运行状态和有效结果。失败先看右侧诊断，确认停止阶段及对象。

## 曲线与结果

- **看最近一段**（曲线默认只看 10 秒）。用「工具 → 设置 → 曲线」设默认查看范围。重新打开曲线后检查显示时段。曲线内可拖动、滚轮缩放，鼠标位于坐标轴时可调对应轴。
- **导出整段精简曲线**（全览 CSV、少留平稳点）。用「文件 → 导出 → 曲线查看与出图」，选运行来源和量值，点「适合全部」，再点「导出精简 CSV」。核对页面给出的实际保留样本起止时刻与导出提示。全览使用已保留的样本。
- **导入曲线数据**（重看以前的曲线）。用「文件 → 导出 → 导入曲线数据文件」，选择曲线数据文件，再选量值。检查来源和可用时段。

## 工况、选配与出图

- **基础计算和应用候选**（两个缸是否同时动、泵够不够）。打开「工具 → 计算 → 基础计算」。在「工况与目标」选择参与动作并填写目标，核算后去「方案比较」查看缺口和候选。只有当前有效候选可应用，应用后核对实际变更。
- **导出计算书和选型任务书**（GB 选型、Word、Markdown）。在基础计算的「选型与导出」选择内容，核对来源后进入导出界面。运行有有效结果时也可用「文件 → 导出 → 计算书（所选有效结果）」。核对已算和待核状态，泵规格备选以任务书所列条件为准。
- **原理图、图框与默认位置**（PDF 或 SVG、换纸张和图框）。用「文件 → 导出 → 原理图」，在「输出设置」选格式、纸张和方向，在「图框模板」选用或保存命名模板。默认值在「工具 → 设置 → 导出」。当次导出可临时改，完成后核对文件实际位置。

## 诊断与 AI 协作

- **排查刚才的报错**（哪个油口没接、为什么不能运行）。先看右侧诊断卡。通过「查看详情」看下一步，按需定位或复制本次报错。若右侧未显示诊断，从「工具 → 诊断与操作记录」打开。详见[诊断与 AI 说明](诊断与AI说明.md)。
- **把工程加入 AI 工作区**（怎么问操作、怎么查当前工程）。加入完整工程目录，通过根 AI.md 和工程.hydproj 定位资料。操作问答读取手册。问现场故障时可以粘贴当前诊断，或使用已授权的实时连接。修改沿工作台预览与确认流程。
`;
}
